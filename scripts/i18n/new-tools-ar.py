import json

PATH = 'messages/ar.json'
data = json.load(open(PATH, encoding='utf-8'))


def add(path, value):
    parts = path.split('.')
    node = data
    for part in parts[:-1]:
        node = node.setdefault(part, {})
    if parts[-1] in node:
        print('skip (exists):', path)
        return
    node[parts[-1]] = value


