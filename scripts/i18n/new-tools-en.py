PATH = 'messages/en.json'
data = json.load(open(PATH, encoding='utf-8'))


def set_path(obj, path, value):
    parts = path.split('.')
    node = obj
    for part in parts[:-1]:
        if not isinstance(node.get(part), dict):
            node[part] = {}
        node = node[part]
    node[parts[-1]] = value


def add(path, value):
    parts = path.split('.')
    node = data
    for part in parts[:-1]:
        node = node.setdefault(part, {})
    if parts[-1] in node:
        print('skip (exists):', path)
        return
    node[parts[-1]] = value


